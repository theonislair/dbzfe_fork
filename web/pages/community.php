        </div>
        
        <div class="guidelines-section fair-play">
            <h3>⚖️ Fair Play</h3>
            <ul>
                <li>No cheating, exploiting, or using unauthorized tools</li>
                <li>Report bugs rather than exploiting them</li>
                <li>Play your character consistently within their role</li>
                <li>Respect PvP etiquette and challenge systems</li>
                <li>Don't monopolize shared resources</li>
            </ul>
        </div>
        
        <div class="guidelines-section communication">
            <h3>💬 Communication Standards</h3>
