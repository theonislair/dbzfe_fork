            <p><strong>Best Against:</strong> Melee combos and heavy attacks</p>
        </div>
        
        <div class="defense-card">
            <h3>🤸 Dodging</h3>
            <div class="defense-options">
                <code>dodge left</code> - Sidestep attacks to the left
                <br>
                <code>dodge right</code> - Sidestep attacks to the right
                <br>
                <code>duck</code> - Avoid high attacks
                <br>
                <code>jump</code> - Leap over low attacks
            </div>
            <p><strong>Effect:</strong> Completely avoid attacks, costs energy</p>
            <p><strong>Best Against:</strong> Predictable attack patterns</p>
        </div>
        
        <div class="defense-card">
            <h3>⚡ Energy Defense</h3>
