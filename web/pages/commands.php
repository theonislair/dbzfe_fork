<div class="command-tips">
    <h2>💡 Command Tips</h2>
    
    <div class="tips-grid">
        <div class="tip-card shortcuts">
            <h3>⚡ Shortcuts & Aliases</h3>
            <ul>
                <li>Most commands have short versions (n/north, s/south, etc.)</li>
                <li>Use semicolons to chain commands: <code>n;e;look</code></li>
                <li>Tab completion works for player names and some commands</li>
                <li>Up arrow recalls your previous commands</li>
                <li>Type <code>commands</code> in-game for a full list</li>
            </ul>
        </div>
        
        <div class="tip-card targeting">
            <h3>🎯 Targeting Tips</h3>
            <ul>
                <li>Use partial names: <code>punch gok</code> for Goku</li>
                <li>Use numbers for multiple targets: <code>look 2.goku</code></li>
                <li>Some commands work without specifying targets</li>
                <li>Case doesn't matter: <code>PUNCH goku</code> works</li>
                <li>Use quotes for multi-word targets: <code>get "senzu bean"</code></li>
            </ul>
        </div>
        
        <div class="tip-card efficiency">
            <h3>🚀 Efficiency Tips</h3>
            <ul>
                <li>Learn keyboard shortcuts for faster commands</li>
                <li>Set up aliases for commonly used command combinations</li>
                <li>Use macros for complex combat sequences</li>
                <li>Practice command timing for combat effectiveness</li>
                <li>Remember: speed matters in PvP combat!</li>
