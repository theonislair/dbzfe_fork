<div class="progression-tips">
    <h2>💡 Progression Tips</h2>
    
    <div class="tips-sections">
        <div class="tip-section efficiency">
            <h3>⚡ Training Efficiency</h3>
            <ul>
                <li><strong>Train Smart:</strong> Fight opponents near your power level for best gains</li>
                <li><strong>Rest Periods:</strong> Don't overtrain - take breaks to maximize gains</li>
                <li><strong>Variety:</strong> Mix different training methods for balanced growth</li>
                <li><strong>Equipment:</strong> Use gravity machines and weighted clothing</li>
                <li><strong>Partners:</strong> Sparring partners provide consistent training</li>
            </ul>
        </div>
        
        <div class="tip-section strategy">
            <h3>🎯 Strategic Planning</h3>
            <ul>
                <li><strong>Goals:</strong> Set short and long-term power level targets</li>
                <li><strong>Skills First:</strong> Learn techniques before purely focusing on power</li>
                <li><strong>Transform Timing:</strong> Don't rush transformations - master your current form</li>
                <li><strong>Planet Hopping:</strong> Travel to find stronger opponents and teachers</li>
                <li><strong>Death Recovery:</strong> Plan for setbacks and how to recover quickly</li>
            </ul>
        </div>
        
        <div class="tip-section safety">
            <h3>🛡️ Staying Safe</h3>
            <ul>
                <li><strong>Escape Plans:</strong> Always have an exit strategy in dangerous fights</li>
                <li><strong>Senzu Beans:</strong> Keep healing items for emergencies</li>
                <li><strong>Safe Zones:</strong> Know where to retreat and recover</li>
                <li><strong>Death Penalty:</strong> Remember death has consequences - avoid unnecessary risks</li>
                <li><strong>Equipment Backup:</strong> Keep spare gear in case of damage</li>
            </ul>
        </div>
    </div>
