<div class="common-mistakes">
    <h2>⚠️ Common Beginner Mistakes</h2>
    
    <div class="mistakes-list">
        <div class="mistake-item">
            <h3>❌ Fighting Too Strong Opponents</h3>
            <p>Don't attack players/NPCs with much higher power levels. You'll die quickly and lose progress. Start small and work your way up.</p>
        </div>
        
        <div class="mistake-item">
            <h3>❌ Ignoring Energy Management</h3>
            <p>Running out of energy in combat is deadly. Watch your energy levels and learn to balance attacks with recovery.</p>
        </div>
        
        <div class="mistake-item">
            <h3>❌ Not Learning Defenses</h3>
            <p>Many new players only focus on attacks. Learning to dodge, parry, and deflect is equally important for survival.</p>
        </div>
        
        <div class="mistake-item">
            <h3>❌ Poor Alignment Choice</h3>
            <p>Choosing alignment based on "good vs evil" instead of preferred techniques. Pick based on which attacks you want to learn.</p>
        </div>
    </div>
